"""Slice a few real rows out of a generated ASSERT test set for a smoke run.

A full suite is 25 prompt + 25 scenario cases, and plumbing errors (wrong
``callable``, missing credentials, a target that raises on its first tool call,
a tool-schema mismatch, an undeployed judge model) only surface once inference
starts. This module lets the skill validate a config on a handful of *real*
cases first, then run the full suite unchanged.

Why slicing, and not a smaller ``sample_size``
----------------------------------------------
Lowering ``pipeline.test_set.prompt.sample_size`` does not work for this. The
raw ``pipeline.test_set`` block feeds the stage's ``config_hash``, so changing it
invalidates the cached test set (and, transitively, inference and judge). It
also does not produce a subset: under ``sampling.method: pairwise`` the sample
size is divided across the covering-array tuples, so a small value drops most
tuples entirely, and case text is regenerated by fresh model calls. You would
validate cases that never appear in the real run, then pay to regenerate it.

Pointing ``pipeline.inference.test_set_path`` at a slice of the *already
generated* test set avoids both problems: ``pipeline.test_set`` is untouched, so
the full run is still a cache hit, and the smoke cases are literally rows the
full run will score.

Design notes
------------
* The current test set is resolved through the suite's ``latest.json`` pointer,
  which is what ASSERT itself writes and reads. Artifact version directories
  (``v0001``, ``v0002``, …) are allocated fresh on every cache miss, so they are
  never assumed.
* Rows are copied as raw text rather than re-serialised, so the slice is
  byte-identical to the corresponding lines of the source test set.
* The output path may not land inside the suite root. Writing there could
  overwrite the published ``test_set.jsonl`` and corrupt the cache the smoke run
  exists to protect.
* ``--suite`` is a suite *identifier*, not a path. It is joined onto
  ``results_dir`` and interpolated into the default output filename, so it is
  validated against the same slug rule ASSERT uses and the resolved suite root
  is required to stay under ``results_dir``.
* ``resolve_results_dir`` mirrors ``assert_ai.config._resolve_path``, including
  its artifact-root prefix stripping, so ``--config`` points at the same tree
  ASSERT would use. It is mirrored rather than imported because
  ``assert_ai.config`` pulls in PyYAML at module scope, which would break the
  stdlib-only ``--suite`` path below.
* Stdlib only, except for an optional PyYAML import used when ``--config`` is
  passed. ``--suite`` needs no third-party package at all.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# Mirrors assert_ai.core.artifact_cache.{LATEST_FILE,ARTIFACTS_DIR} and
# assert_ai.stages.test_set.TEST_SET_FILE.
LATEST_FILE = "latest.json"
ARTIFACTS_DIR = "artifacts"
TEST_SET_FILE = "test_set.jsonl"

# Mirrors assert_ai.config._SAFE_ID_RE, which itself must match the viewer's
# SAFE_ID_RE in artifacts.ts: /^[a-z0-9][a-z0-9._-]*$/i
_SAFE_ID_RE = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9._-]*$")

KINDS = ("prompt", "scenario")
DEFAULT_COUNT = 3


class SmokeSliceError(Exception):
    """Raised for user-correctable problems, reported without a traceback."""


def validate_suite_id(value: str) -> str:
    """Reject suite ids that are not safe slugs.

    Mirrors ``assert_ai.config._validate_identifier``. ``suite`` is an
    identifier, never a path: it is joined onto ``results_dir``, and it also
    feeds the default output filename. Without this, an absolute path or a
    ``..`` segment would read from — and write to — an arbitrary location.
    """

    if not value:
        raise SmokeSliceError("suite must not be empty")
    if len(value) > 255:
        raise SmokeSliceError("suite exceeds maximum length of 255 characters")
    if ".." in value:
        raise SmokeSliceError("suite must not contain '..'")
    if not _SAFE_ID_RE.match(value):
        raise SmokeSliceError(
            "suite must start with an alphanumeric character and contain only "
            f"alphanumerics, dots, hyphens, or underscores; got: {value!r}"
        )
    return value


def _repo_root() -> Path:
    """Repository root, four levels up from .claude/skills/run-assert-eval/."""

    return Path(__file__).resolve().parents[3]


def load_config(config_path: str | Path) -> dict:
    """Read an eval config. Requires PyYAML; use ``--suite`` to avoid it."""

    try:
        import yaml
    except ImportError as exc:  # pragma: no cover - depends on environment
        raise SmokeSliceError(
            "PyYAML is not installed, so --config cannot be read. "
            "Pass --suite <suite-id> (and --results-dir if non-default) instead."
        ) from exc

    path = Path(config_path)
    if not path.is_file():
        raise SmokeSliceError(f"config not found: {path}")
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise SmokeSliceError(f"config is not a YAML mapping: {path}")
    return raw


def _strip_artifact_root_prefix(path: Path, artifacts_root: Path) -> Path | None:
    """Return the artifact-relative suffix for paths starting with an artifacts root.

    Mirrors ``assert_ai.config._strip_artifact_root_prefix``.
    """

    parts = path.parts
    if not parts:
        return None
    if parts[0] not in {ARTIFACTS_DIR, artifacts_root.name}:
        return None
    if len(parts) == 1:
        return Path()
    return Path(*parts[1:])


def resolve_results_dir(raw: dict, *, root: Path | None = None) -> Path:
    """Resolve ``results_dir`` the way assert_ai.config does.

    Mirrors ``assert_ai.config._resolve_path(..., use_artifacts_root=True)``,
    including its artifact-root prefix stripping. That stripping is what keeps
    a config like ``artifacts_root: artifacts`` plus ``results_dir:
    artifacts/custom`` resolving to ``<root>/artifacts/custom`` rather than
    ``<root>/artifacts/artifacts/custom`` — the latter would send ``--config``
    looking in a tree ASSERT never writes to.
    """

    root = root or _repo_root()
    artifacts_root = Path(str(raw.get("artifacts_root") or ARTIFACTS_DIR)).expanduser()
    if not artifacts_root.is_absolute():
        artifacts_root = (root / artifacts_root).resolve()
    else:
        artifacts_root = artifacts_root.resolve()

    results_dir_raw = raw.get("results_dir")
    if not results_dir_raw:
        return (artifacts_root / "results").resolve()

    candidate = Path(str(results_dir_raw)).expanduser()
    if candidate.is_absolute():
        # Absolute paths are explicitly specified by the user; allow them, as
        # assert_ai.config does. The suite-id validation and the suite_root
        # containment check still bound everything opened underneath.
        return candidate.resolve()

    artifact_relative = _strip_artifact_root_prefix(candidate, artifacts_root)
    resolved = (
        artifacts_root / artifact_relative
        if artifact_relative is not None
        else artifacts_root / candidate
    ).resolve()
    if not _is_within(resolved, artifacts_root):
        raise SmokeSliceError(
            f"results_dir escapes its artifacts root ({artifacts_root}): {results_dir_raw!r}"
        )
    return resolved


def resolve_test_set(suite_root: Path) -> tuple[Path, str]:
    """Locate the current test set for a suite.

    Prefers the ``latest.json`` pointer ASSERT maintains, and falls back to the
    copy published at the suite root. Returns the path and how it was found.
    """

    if not suite_root.is_dir():
        raise SmokeSliceError(
            f"suite root not found: {suite_root}\n"
            "Generate the test set first:\n"
            "  assert-ai run --config <config> "
            "--override inference.enabled=false --override judge.enabled=false"
        )

    latest_path = suite_root / LATEST_FILE
    if latest_path.is_file():
        try:
            latest = json.loads(latest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            latest = None
        if isinstance(latest, dict):
            ref = (latest.get("artifacts") or {}).get("test_set") or {}
            relative = ref.get("path")
            if relative:
                candidate = (suite_root / str(relative)).resolve()
                if _is_within(candidate, suite_root) and candidate.is_file():
                    return candidate, f"{LATEST_FILE} -> {relative}"

    published = suite_root / TEST_SET_FILE
    if published.is_file():
        return published.resolve(), f"published {TEST_SET_FILE}"

    raise SmokeSliceError(
        f"no test set found under {suite_root}\n"
        "Generate it first:\n"
        "  assert-ai run --config <config> "
        "--override inference.enabled=false --override judge.enabled=false"
    )


def _is_within(candidate: Path, base: Path) -> bool:
    try:
        return candidate.resolve().is_relative_to(base.resolve())
    except OSError:  # pragma: no cover - defensive
        return False


def select_rows(lines: list[str], kind: str, count: int) -> tuple[list[str], list[str], int]:
    """Return (selected raw lines, their test_case_ids, total rows of that kind).

    Malformed lines are skipped rather than fatal: the test set is generated
    upstream, and a smoke run should surface a bad target, not die on one
    unparseable row.
    """

    selected: list[str] = []
    case_ids: list[str] = []
    available = 0

    for line in lines:
        text = line.strip()
        if not text:
            continue
        try:
            row = json.loads(text)
        except json.JSONDecodeError:
            continue
        if not isinstance(row, dict) or row.get("type") != kind:
            continue
        available += 1
        if len(selected) < count:
            selected.append(text)
            case_ids.append(str(row.get("test_case_id", "")))

    return selected, case_ids, available


def build_slice(
    *,
    suite: str,
    results_dir: Path,
    kind: str = "prompt",
    count: int = DEFAULT_COUNT,
    out_path: Path | None = None,
) -> dict:
    """Write a smoke slice and return a summary describing what was written."""

    if kind not in KINDS:
        raise SmokeSliceError(f"kind must be one of {', '.join(KINDS)}; got {kind!r}")
    if count < 1:
        raise SmokeSliceError(f"count must be at least 1; got {count}")

    # `suite` is an identifier, not a path. Validate before it is joined onto
    # results_dir or interpolated into the default output filename.
    suite = validate_suite_id(str(suite))

    results_dir = Path(results_dir).expanduser().resolve()
    suite_root = (results_dir / suite).resolve()
    if not _is_within(suite_root, results_dir):
        raise SmokeSliceError(
            f"suite_root escapes its expected root directory ({results_dir}): {suite_root}"
        )

    source, resolved_via = resolve_test_set(suite_root)

    lines = source.read_text(encoding="utf-8").splitlines()
    selected, case_ids, available = select_rows(lines, kind, count)
    if not selected:
        raise SmokeSliceError(
            f"no rows of type {kind!r} in {source}. "
            f"Check that pipeline.test_set.{kind} is configured."
        )

    if out_path is None:
        out_path = _repo_root() / ARTIFACTS_DIR / "smoke" / f"{suite}-{kind}-{len(selected)}.jsonl"
    out_path = Path(out_path).expanduser().resolve()

    # Writing inside the suite root could clobber the published test set and
    # invalidate the very cache this slice exists to preserve.
    if _is_within(out_path, suite_root):
        raise SmokeSliceError(
            f"refusing to write inside the suite root ({suite_root}); "
            "choose an --out path outside it, such as artifacts/smoke/."
        )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(selected) + "\n", encoding="utf-8")

    return {
        "suite": suite,
        "kind": kind,
        "requested": count,
        "written": len(selected),
        "available": available,
        "source": str(source),
        "resolved_via": resolved_via,
        "out": str(out_path),
        "test_case_ids": case_ids,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Slice N real rows from a generated ASSERT test set for a smoke run.",
    )
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--config", help="Eval config to read `suite` and `results_dir` from.")
    source.add_argument("--suite", help="Suite id, if you would rather not read the config.")
    parser.add_argument(
        "--results-dir",
        help="Overrides the config value. Defaults to <artifacts_root>/results.",
    )
    parser.add_argument("--kind", choices=KINDS, default="prompt", help="Default: prompt.")
    parser.add_argument(
        "--count", type=int, default=DEFAULT_COUNT, help=f"Default: {DEFAULT_COUNT}."
    )
    parser.add_argument(
        "--out",
        help="Output path. Defaults to artifacts/smoke/<suite>-<kind>-<n>.jsonl.",
    )
    args = parser.parse_args(argv)

    try:
        if args.config:
            raw = load_config(args.config)
            suite = raw.get("suite")
            if not suite:
                raise SmokeSliceError(f"config has no `suite` key: {args.config}")
            results_dir = (
                Path(args.results_dir).expanduser().resolve()
                if args.results_dir
                else resolve_results_dir(raw)
            )
        else:
            suite = args.suite
            results_dir = (
                Path(args.results_dir).expanduser().resolve()
                if args.results_dir
                else resolve_results_dir({})
            )

        summary = build_slice(
            suite=str(suite),
            results_dir=results_dir,
            kind=args.kind,
            count=args.count,
            out_path=Path(args.out) if args.out else None,
        )
    except SmokeSliceError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print(json.dumps(summary, indent=2))
    if summary["written"] < summary["requested"]:
        print(
            f"note: only {summary['written']} {summary['kind']} row(s) available, "
            f"requested {summary['requested']}.",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
